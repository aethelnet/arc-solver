def extract_foveated_patch(
    frame_or_grid: Any,
    center: Tuple[int, int],
    radius: int = 4
) -> Dict[str, Any]:
    """
    Extracts an (2*radius + 1) x (2*radius + 1) local window centered at center=(r, c).
    Pads out-of-bounds with '#' boundary indicator.
    """
    lines = _to_lines(frame_or_grid)
    H = len(lines)
    W = len(lines[0]) if H > 0 else 0
    cr, cc = center
    r1, r2 = cr - radius, cr + radius
    c1, c2 = cc - radius, cc + radius

    patch_lines = []
    for r in range(r1, r2 + 1):
        row_chars = []
        for c in range(c1, c2 + 1):
            if 0 <= r < H and 0 <= c < W:
                row_chars.append(lines[r][c])
            else:
                row_chars.append('#')
        patch_lines.append("".join(row_chars))

    return {
        "r1": r1,
        "c1": c1,
        "r2": r2,
        "c2": c2,
        "center": (cr, cc),
        "lines": patch_lines,
        "ascii": "\n".join(patch_lines)
    }


def format_macro_radar(
    entities: List[OntologyEntity],
    avatar_pos: Optional[Tuple[int, int]] = None
) -> str:
    """
    Generates an ultra-compact semantic radar (<40 tokens) mapping
    relative offsets and Manhattan distances from the avatar to key landmarks.
    """
    if not entities:
        return ""
    lines = ["=== AETHELNET MACRO-RADAR ==="]
    if avatar_pos is not None:
        lines.append(f"- AVATAR: at {avatar_pos}")

    targets = [e for e in entities if e.archetype in ("GOAL", "PUSHABLE", "ACTUATOR", "GATE", "HAZARD")]
    if avatar_pos is not None:
        targets.sort(key=lambda e: abs(e.center[0] - avatar_pos[0]) + abs(e.center[1] - avatar_pos[1]))

    for e in targets[:5]:
        if avatar_pos is not None:
            dr = e.center[0] - avatar_pos[0]
            dc = e.center[1] - avatar_pos[1]
            dist = abs(dr) + abs(dc)
            lines.append(f"- {e.archetype} #{e.id} (col '{e.color}'): at {e.center} [Offset: ({dr:+d}, {dc:+d}), Dist: {dist}]")
        else:
            lines.append(f"- {e.archetype} #{e.id} (col '{e.color}'): at {e.center}")

    lines.append("=============================")
    return "\n".join(lines)


def track_entity_velocities(
    prev_entities: List[OntologyEntity],
    curr_entities: List[OntologyEntity]
) -> List[Dict[str, Any]]:
    """
    Computes velocity vectors v = (dr, dc) across consecutive frames
    for matching non-HUD entities.
    """
    velocities = []
    for ce in curr_entities:
        if ce.archetype in ("HUD", "OBSTACLE"):
            continue
        best_match = None
        min_dist = 999
        for pe in prev_entities:
            if pe.color == ce.color and pe.archetype == ce.archetype:
                d = abs(ce.center[0] - pe.center[0]) + abs(ce.center[1] - pe.center[1])
                if d < min_dist and d <= 6:
                    min_dist = d
                    best_match = pe
        if best_match is not None and min_dist > 0:
            dr = ce.center[0] - best_match.center[0]
            dc = ce.center[1] - best_match.center[1]
            dir_name = "STATIONARY"
            if dr < 0 and dc == 0: dir_name = "UP"
            elif dr > 0 and dc == 0: dir_name = "DOWN"
            elif dr == 0 and dc < 0: dir_name = "LEFT"
            elif dr == 0 and dc > 0: dir_name = "RIGHT"
            elif dr < 0 and dc > 0: dir_name = "UP_RIGHT"
            elif dr < 0 and dc < 0: dir_name = "UP_LEFT"
            elif dr > 0 and dc > 0: dir_name = "DOWN_RIGHT"
            elif dr > 0 and dc < 0: dir_name = "DOWN_LEFT"

            velocities.append({
                "entity_id": ce.id,
                "color": ce.color,
                "archetype": ce.archetype,
                "pos": ce.center,
                "velocity": (dr, dc),
                "direction": dir_name
            })
    return velocities


def simulate_step(
    frame_or_grid: Any,
    action: Union[int, str],
    avatar_pos: Optional[Tuple[int, int]] = None
) -> Tuple[List[str], bool, List[str]]:
    """
    Performs a deterministic 1-step virtual simulation of action from avatar_pos.
    Returns (predicted_lines, is_deadlock, event_log).
    """
    lines = [list(row) for row in _to_lines(frame_or_grid)]
    H = len(lines)
    W = len(lines[0]) if H > 0 else 0
    if H == 0 or W == 0 or action not in ACTION_TO_DIR:
        return ["".join(r) for r in lines], False, ["Invalid action or empty frame"]

    dr, dc = ACTION_TO_DIR[action]
    events = []

    bg, entities = AethelnetGameOntology.extract_entities(frame_or_grid)
    ar, ac = avatar_pos if avatar_pos is not None else (0, 0)
    if avatar_pos is None:
        for e in entities:
            if e.archetype == "ACTUATOR":
                ar, ac = e.center
                break

    nr, nc = ar + dr, ac + dc
    if not (0 <= nr < H and 0 <= nc < W):
        events.append("Hit board boundary")
        return ["".join(r) for r in lines], False, events

    target_char = lines[nr][nc]
    is_deadlock = False

    cargos = [e for e in entities if e.archetype in ("PUSHABLE", "ACTUATOR") and not e.is_hollow and e.center != (ar, ac)]
    matching_cargo = None
    for c in cargos:
        r1, c1, r2, c2 = c.bbox
        if r1 <= nr <= r2 and c1 <= nc <= c2:
            matching_cargo = c
            break

    if matching_cargo is not None:
        deadlock, reason = evaluate_push_deadlock(frame_or_grid, matching_cargo.bbox, action)
        if deadlock:
            is_deadlock = True
            events.append(f"Push causes deadlock: {reason}")
        else:
            events.append(f"Pushed cargo #{matching_cargo.id} in direction {action}")
            lines[nr][nc] = bg
            target_br, target_bc = matching_cargo.center[0] + dr, matching_cargo.center[1] + dc
            if 0 <= target_br < H and 0 <= target_bc < W:
                lines[target_br][target_bc] = matching_cargo.color
    elif target_char != bg and target_char not in ('.', '0'):
        events.append(f"Collided with obstacle '{target_char}'")
    else:
        events.append(f"Avatar moved to ({nr}, {nc})")

    return ["".join(r) for r in lines], is_deadlock, events


