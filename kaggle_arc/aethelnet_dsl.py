# 5. Galois Field GF(k) Modular Linear Solver
# =============================================================================

def solve_modular_linear_system(
    A: np.ndarray,
    b: np.ndarray,
    k: int = 2
) -> Optional[np.ndarray]:
    """
    Exact Gaussian elimination solving A x ≡ b (mod k).
    Used for toggle switches, light bulbs, parity constraints, and GF(2) circuits.
    Minimizes total switch clicks sum(x).
    """
    A = np.asarray(A, dtype=int) % k
    b = np.asarray(b, dtype=int).flatten() % k
    n_rows, n_cols = A.shape
    M = np.hstack([A, b.reshape(-1, 1)]) % k

    row = 0
    pivots = []
    pivot_cols = set()

    for col in range(n_cols):
        p = None
        for r in range(row, n_rows):
            val = int(M[r, col] % k)
            if val != 0:
                if math.gcd(val, k) == 1:
                    p = r
                    break
                elif p is None:
                    p = r
        if p is None:
            continue

        M[[row, p]] = M[[p, row]]
        pivot_val = int(M[row, col])
        try:
            inv = pow(pivot_val, -1, k)
        except ValueError:
            continue

        M[row] = (M[row] * inv) % k
        for r in range(n_rows):
            if r != row and M[r, col] % k != 0:
                factor = M[r, col]
                M[r] = (M[r] - factor * M[row]) % k
        pivots.append((row, col))
        pivot_cols.add(col)
        row += 1

    # Consistency check
    for r in range(row, n_rows):
        if M[r, -1] % k != 0:
            return None

    free_cols = [c for c in range(n_cols) if c not in pivot_cols]

    if not free_cols:
        x_sol = np.zeros(n_cols, dtype=int)
        for r, col in reversed(pivots):
            x_sol[col] = (M[r, -1] - np.dot(M[r, :n_cols], x_sol)) % k
        return x_sol

    # Multiple solutions exist: search nullspace minimizing sum(x)
    best_x = None
    min_clicks = float('inf')
    max_search = min(len(free_cols), 6)

    for free_vals in itertools.product(range(k), repeat=max_search):
        x_cand = np.zeros(n_cols, dtype=int)
        for i, val in enumerate(free_vals):
            x_cand[free_cols[i]] = val
        for r, col in reversed(pivots):
            x_cand[col] = (M[r, -1] - np.dot(M[r, :n_cols], x_cand)) % k

        clicks = int(np.sum(x_cand))
        if clicks < min_clicks:
            min_clicks = clicks
            best_x = x_cand

    return best_x


