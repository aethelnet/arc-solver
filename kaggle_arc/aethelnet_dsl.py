# 3. Pathfinding (BFS / A*)
# =============================================================================

def plan_bfs_path(
    start_pos: Tuple[int, int],
    target_pos: Tuple[int, int],
    solid_mask: np.ndarray,
    stride: int = 1,
    deadly_coords: Optional[Set[Tuple[int, int]]] = None,
    legal_actions: Optional[List[Any]] = None,
    as_strings: bool = True
) -> List[Any]:
    """
    Sub-millisecond BFS grid pathfinding over arbitrary solid obstacles & fatal tiles.
    """
    sr, sc = start_pos
    tr, tc = target_pos
    s = stride
    if solid_mask is None or not hasattr(solid_mask, "shape") or len(solid_mask.shape) != 2:
        return []
    H, W = solid_mask.shape
    hazards = deadly_coords or set()

    q = [(sr, sc, [])]
    visited = {(sr, sc)}

    allowed_moves = [1, 2, 3, 4]
    if legal_actions:
        allowed_moves = [
            DIR_TO_ACTION_INT[ACTION_TO_DIR[a]]
            for a in legal_actions
            if a in ACTION_TO_DIR
        ]

    while q:
        cr, cc, path = q.pop(0)
        if abs(cr - tr) < s and abs(cc - tc) < s:
            if as_strings:
                return [DIR_TO_ACTION_NAME[ACTION_TO_DIR[act]] for act in path]
            return path

        if len(path) > 120:
            continue

        for act in allowed_moves:
            dr, dc = ACTION_TO_DIR[act]
            nr, nc = cr + dr * s, cc + dc * s

            if 0 <= nr <= H - s and 0 <= nc <= W - s:
                if np.any(solid_mask[nr:nr + s, nc:nc + s]):
                    continue
                if (nr, nc) in hazards:
                    continue
                if (nr, nc) not in visited:
                    visited.add((nr, nc))
                    q.append((nr, nc, path + [act]))

    return []


