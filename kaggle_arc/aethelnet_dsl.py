@dataclass
class MacroIntent:
    name: str  # 'NAVIGATE_TO', 'PUSH_BOX', 'ACTUATE_SWITCH', 'INTERACT'
    target: Optional[Tuple[int, int]] = None
    box_pos: Optional[Tuple[int, int]] = None
    direction: Optional[str] = None  # 'UP', 'DOWN', 'LEFT', 'RIGHT'
    entity_id: Optional[int] = None
    params: Dict[str, Any] = field(default_factory=dict)


@dataclass
class MacroChainResult:
    success: bool
    actions: List[Dict[str, Any]]
    action_names: List[str]
    reason: str
    step_count: int


class AethelnetMacroCompiler:
    """Compiles high-level macro intents into verified atomic action sequences."""

    @classmethod
    def compile_intent(
        cls,
        intent: Union[MacroIntent, Dict[str, Any]],
        frame_or_grid: Any,
        solid_mask: Optional[np.ndarray] = None,
        avatar_pos: Optional[Tuple[int, int]] = None,
        stride: int = 1,
        available_actions: Optional[List[Any]] = None
    ) -> MacroChainResult:
        if isinstance(intent, dict):
            intent = MacroIntent(
                name=intent.get("name", intent.get("intent", "")),
                target=intent.get("target"),
                box_pos=intent.get("box_pos"),
                direction=intent.get("direction"),
                entity_id=intent.get("entity_id"),
                params=intent.get("params", {})
            )

        lines = _to_lines(frame_or_grid)
        H = len(lines)
        W = len(lines[0]) if H > 0 else 0
        if H == 0 or W == 0:
            return MacroChainResult(False, [], [], "EmptyGrid", 0)

        # 0. Defensive parameter resolution for solid_mask / available_actions
        if isinstance(solid_mask, (list, tuple)) and solid_mask and not isinstance(solid_mask[0], (list, tuple, np.ndarray)):
            if available_actions is None:
                available_actions = list(solid_mask)
            solid_mask = None

        if solid_mask is not None:
            if isinstance(solid_mask, np.ndarray) and solid_mask.ndim == 2 and solid_mask.shape == (H, W):
                solid_mask = solid_mask.copy()
            else:
                try:
                    sm = np.asarray(solid_mask, dtype=bool)
                    if sm.ndim == 2 and sm.shape == (H, W):
                        solid_mask = sm.copy()
                    else:
                        solid_mask = None
                except Exception:
                    solid_mask = None

        # 1. Resolve Avatar Position if not explicitly given
        if avatar_pos is None:
            _, entities = AethelnetGameOntology.extract_entities(frame_or_grid)
            av_entity = next((e for e in entities if e.archetype in ("AVATAR", "ACTUATOR")), None)
            if av_entity:
                avatar_pos = av_entity.center
            else:
                avatar_pos = (H // 2, W // 2)

        # 2. Build or resolve solid_mask
        if solid_mask is None:
            solid_mask = np.zeros((H, W), dtype=bool)
            bg, entities = AethelnetGameOntology.extract_entities(frame_or_grid)
            for r in range(H):
                for c in range(W):
                    if lines[r][c] != bg and lines[r][c] not in ('.', '0'):
                        solid_mask[r, c] = True
            # Avatar tile itself is walkable
            if 0 <= avatar_pos[0] < H and 0 <= avatar_pos[1] < W:
                solid_mask[avatar_pos[0], avatar_pos[1]] = False

        intent_name = (intent.name or "").upper()

        # CASE 1: NAVIGATE_TO
        if intent_name in ("NAVIGATE_TO", "NAVIGATE", "MOVE_TO"):
            target = intent.target
            if target is None:
                return MacroChainResult(False, [], [], "MissingTarget", 0)
            tr, tc = target
            if not (0 <= tr < H and 0 <= tc < W):
                return MacroChainResult(False, [], [], "TargetOutOfBounds", 0)

            # Ensure target tile is temporarily marked walkable for path search
            orig_solid = solid_mask[tr, tc]
            solid_mask[tr, tc] = False
            raw_path = plan_bfs_path(avatar_pos, (tr, tc), solid_mask, stride=stride, as_strings=False)
            solid_mask[tr, tc] = orig_solid

            if not raw_path:
                if abs(avatar_pos[0] - tr) < stride and abs(avatar_pos[1] - tc) < stride:
                    return MacroChainResult(True, [], [], "AlreadyAtTarget", 0)
                return MacroChainResult(False, [], [], "PathNotFound", 0)

            action_names = [ACTION_TO_NAME.get(m, DIR_TO_ACTION_NAME.get(ACTION_TO_DIR.get(m, (0, 0)), 'UP')) for m in raw_path]
            actions = [{"action": DIR_TO_ACTION_NAME.get(ACTION_TO_DIR.get(m, (0, 0)), 'ACTION1')} for m in raw_path]
            return MacroChainResult(True, actions, action_names, "NavigationSuccess", len(actions))

        # CASE 2: PUSH_BOX
        elif intent_name in ("PUSH_BOX", "PUSH"):
            box_pos = intent.box_pos or intent.target
            if isinstance(box_pos, (list, np.ndarray)):
                box_pos = tuple(box_pos)
            direction = (intent.direction or "UP").upper()
            if box_pos is None:
                return MacroChainResult(False, [], [], "MissingBoxPos", 0)

            dir_map = {"UP": (-1, 0), "DOWN": (1, 0), "LEFT": (0, -1), "RIGHT": (0, 1)}
            if direction not in dir_map:
                return MacroChainResult(False, [], [], f"InvalidDirection_{direction}", 0)
            dr, dc = dir_map[direction]

            # Deadlock check: does pushing box in this direction cause corner deadlock?
            deadlock, reason = evaluate_push_deadlock(frame_or_grid, box_pos, direction, solid_mask=solid_mask)
            if deadlock:
                return MacroChainResult(False, [], [], f"DeadlockVeto_{reason}", 0)

            # Push pose: tile directly opposite to push direction
            push_pose = (box_pos[0] - dr * stride, box_pos[1] - dc * stride)
            if not (0 <= push_pose[0] < H and 0 <= push_pose[1] < W):
                return MacroChainResult(False, [], [], "PushPoseOutOfBounds", 0)

            # Route avatar to push_pose avoiding box
            box_barrier = solid_mask.copy()
            box_barrier[box_pos[0], box_pos[1]] = True
            box_barrier[push_pose[0], push_pose[1]] = False

            nav_moves = plan_bfs_path(avatar_pos, push_pose, box_barrier, stride=stride, as_strings=False)
            if avatar_pos != push_pose and not nav_moves:
                return MacroChainResult(False, [], [], "CannotReachPushPose", 0)

            push_act_int = DIR_TO_ACTION_INT.get((dr, dc), 1)
            total_moves = nav_moves + [push_act_int]
            action_names = [ACTION_TO_NAME.get(m, 'UP') for m in total_moves]
            actions = [{"action": DIR_TO_ACTION_NAME.get(ACTION_TO_DIR.get(m, (0, 0)), 'ACTION1')} for m in total_moves]
            return MacroChainResult(True, actions, action_names, "PushPlanSuccess", len(actions))

        # CASE 3: ACTUATE_SWITCH / CLICK / INTERACT
        elif intent_name in ("ACTUATE_SWITCH", "ACTUATE", "INTERACT", "MOUSE"):
            target = intent.target
            if target is None:
                return MacroChainResult(False, [], [], "MissingTarget", 0)

            # If parameter specifies MOUSE click:
            if intent_name in ("INTERACT", "MOUSE") or intent.params.get("use_mouse"):
                act = {"action": "MOUSE", "row": target[0], "col": target[1]}
                return MacroChainResult(True, [act], ["MOUSE"], "MouseAction", 1)

            # Check if game supports ACTION5 (Interact/Use)
            has_action5 = False
            if available_actions:
                act_vals = [getattr(a, 'value', a) for a in available_actions]
                has_action5 = (5 in act_vals or "ACTION5" in act_vals)

            # Otherwise, route to adjacent cell and interact
            adj_cells = [
                (target[0] - dr * stride, target[1] - dc * stride)
                for dr, dc in [(-1, 0), (1, 0), (0, -1), (0, 1)]
            ]
            valid_adj = [p for p in adj_cells if 0 <= p[0] < H and 0 <= p[1] < W and not solid_mask[p[0], p[1]]]
            if not valid_adj:
                return MacroChainResult(False, [], [], "SwitchUnreachable", 0)

            # Pick nearest adjacent tile to avatar
            valid_adj.sort(key=lambda p: abs(p[0] - avatar_pos[0]) + abs(p[1] - avatar_pos[1]))
            best_adj = valid_adj[0]

            nav_moves = plan_bfs_path(avatar_pos, best_adj, solid_mask, stride=stride, as_strings=False)

            if has_action5:
                # Face target or trigger ACTION5 interact
                action_names = [ACTION_TO_NAME.get(m, 'UP') for m in nav_moves] + ["ACTION5"]
                actions = [{"action": DIR_TO_ACTION_NAME.get(ACTION_TO_DIR.get(m, (0, 0)), 'ACTION1')} for m in nav_moves] + [{"action": "ACTION5"}]
            else:
                step_to_switch_dr, step_to_switch_dc = target[0] - best_adj[0], target[1] - best_adj[1]
                # Normalize step to unit direction
                norm_dr = 1 if step_to_switch_dr > 0 else (-1 if step_to_switch_dr < 0 else 0)
                norm_dc = 1 if step_to_switch_dc > 0 else (-1 if step_to_switch_dc < 0 else 0)
                act_step = DIR_TO_ACTION_INT.get((norm_dr, norm_dc), 1)
                total_moves = nav_moves + [act_step]
                action_names = [ACTION_TO_NAME.get(m, 'UP') for m in total_moves]
                actions = [{"action": DIR_TO_ACTION_NAME.get(ACTION_TO_DIR.get(m, (0, 0)), 'ACTION1')} for m in total_moves]

            return MacroChainResult(True, actions, action_names, "ActuateSuccess", len(actions))

        return MacroChainResult(False, [], [], f"UnknownIntent_{intent.name}", 0)




