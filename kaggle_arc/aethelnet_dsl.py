def get_background_color(grid: np.ndarray) -> int:
    """Finds dominant background color of the grid."""
    grid = np.asarray(grid)
    vals, counts = np.unique(grid, return_counts=True)
    return int(vals[np.argmax(counts)])


def detect_hud_bars(g0: np.ndarray, g1: np.ndarray, border_band: int = 2) -> Tuple[Set[int], Set[int]]:
    """Identifies border rows and columns that only act as counters/HUD ticks."""
    H, W = g0.shape
    diff = (g0 != g1)
    hud_rows, hud_cols = set(), set()
    if not np.any(diff):
        return hud_rows, hud_cols

    diff_pts = np.argwhere(diff)
    for r, c in diff_pts:
        if r < border_band or r >= H - border_band:
            if 1 <= diff[r, :].sum() <= 4:
                hud_rows.add(r)
        if c < border_band or c >= W - border_band:
            if 1 <= diff[:, c].sum() <= 4:
                hud_cols.add(c)
    return hud_rows, hud_cols


def extract_clickable_targets(
    grid: np.ndarray,
    hud_rows: Optional[Set[int]] = None,
    hud_cols: Optional[Set[int]] = None,
    min_area: int = 4,
    max_area: Optional[int] = None
) -> List[Tuple[int, int]]:
    """
    Identifies centroid (x, y) coordinates of distinct clickable interactive buttons/sprites.
    Returns sorted by rarity (smallest/rarest components first).
    """
    grid = np.asarray(grid)
    H, W = grid.shape
    bg = get_background_color(grid)
    hud_r = hud_rows or set()
    hud_c = hud_cols or set()
    if max_area is None:
        max_area = (H * W) // 4

    visited = np.zeros((H, W), dtype=bool)
    components = []

    for r in range(H):
        for c in range(W):
            if visited[r, c] or grid[r, c] == bg or r in hud_r or c in hud_c:
                continue
            color = grid[r, c]
            q = [(r, c)]
            visited[r, c] = True
            comp_pts = []
            min_r, max_r, min_c, max_c = r, r, c, c

            while q:
                cr, cc = q.pop(0)
                comp_pts.append((cr, cc))
                min_r = min(min_r, cr)
                max_r = max(max_r, cr)
                min_c = min(min_c, cc)
                max_c = max(max_c, cc)

                for dr, dc in [(-1, 0), (1, 0), (0, -1), (0, 1)]:
                    nr, nc = cr + dr, cc + dc
                    if 0 <= nr < H and 0 <= nc < W:
                        if not visited[nr, nc] and grid[nr, nc] == color and nr not in hud_r and nc not in hud_c:
                            visited[nr, nc] = True
                            q.append((nr, nc))

            if min_area <= len(comp_pts) <= max_area:
                center_r = (min_r + max_r) // 2
                center_c = (min_c + max_c) // 2
                components.append((center_c, center_r, len(comp_pts), color))

    components.sort(key=lambda x: (x[2], x[0], x[1]))
    return [(c, r) for c, r, _, _ in components]


