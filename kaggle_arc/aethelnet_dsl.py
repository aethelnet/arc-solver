# 2. Kinematics Induction (Stride, Avatar, Background)
# =============================================================================

class KinematicsProfile:
    def __init__(
        self,
        stride: int = 1,
        avatar_shape: Tuple[int, int] = (1, 1),
        avatar_colors: Optional[Set[int]] = None,
        bg_color: int = 0
    ):
        self.stride = stride
        self.avatar_shape = avatar_shape
        self.avatar_colors = avatar_colors or set()
        self.bg_color = bg_color


def calibrate_kinematics_probe(
    g0: np.ndarray,
    g1: np.ndarray,
    action: Union[int, str]
) -> Optional[KinematicsProfile]:
    """
    Given two consecutive grids (before & after move) and the action executed,
    uses connected component analysis to ground physical stride, avatar bounding box,
    avatar pixel colors, and background color.
    """
    from scipy.ndimage import label
    g0 = np.asarray(g0)
    g1 = np.asarray(g1)
    H, W = g0.shape
    diff = (g0 != g1)
    if not np.any(diff):
        return None

    lbl, n = label(diff)
    best_comp = None
    best_area = -1

    for i in range(1, n + 1):
        comp = np.argwhere(lbl == i)
        area = len(comp)
        if area <= 4:
            continue
        if area > best_area:
            best_area = area
            r0, c0 = comp.min(axis=0)
            r1, c1 = comp.max(axis=0)
            best_comp = (comp, r0, c0, r1, c1, r1 - r0 + 1, c1 - c0 + 1)

    if best_comp is None:
        return None

    comp, r0, c0, r1, c1, h_diff, w_diff = best_comp
    dr, dc = ACTION_TO_DIR.get(action, (0, 0))

    if dr > 0:  # DOWN
        stride = max(1, h_diff // 2)
        old_patch = g1[r0:r0 + stride, c0:c1 + 1]
        new_patch = g1[r0 + stride:r1 + 1, c0:c1 + 1]
        shape = (stride, w_diff)
    elif dr < 0:  # UP
        stride = max(1, h_diff // 2)
        old_patch = g1[r1 - stride + 1:r1 + 1, c0:c1 + 1]
        new_patch = g1[r0:r1 - stride + 1, c0:c1 + 1]
        shape = (stride, w_diff)
    elif dc > 0:  # RIGHT
        stride = max(1, w_diff // 2)
        old_patch = g1[r0:r1 + 1, c0:c0 + stride]
        new_patch = g1[r0:r1 + 1, c0 + stride:c1 + 1]
        shape = (h_diff, stride)
    else:  # LEFT
        stride = max(1, w_diff // 2)
        old_patch = g1[r0:r1 + 1, c1 - stride + 1:c1 + 1]
        new_patch = g1[r0:r1 + 1, c0:c1 - stride + 1]
        shape = (h_diff, stride)

    bg_color = int(np.bincount(old_patch.flatten()).argmax())
    av_colors = set(int(c) for c in np.unique(new_patch)) - {bg_color}
    return KinematicsProfile(stride=stride, avatar_shape=shape, avatar_colors=av_colors, bg_color=bg_color)


def locate_avatar_on_grid(
    grid: np.ndarray,
    profile: KinematicsProfile,
    hud_rows: Optional[Set[int]] = None,
    hud_cols: Optional[Set[int]] = None
) -> Optional[Tuple[int, int]]:
    """Locates top-left (r, c) of the player avatar using induced kinematics."""
    if not profile.avatar_colors:
        return None
    H, W = grid.shape
    ah, aw = profile.avatar_shape
    s = profile.stride
    hud_r = hud_rows or set()
    hud_c = hud_cols or set()

    best_pos = None
    best_score = -1

    for r in range(0, H - ah + 1, s):
        if r in hud_r:
            continue
        for c in range(0, W - aw + 1, s):
            if c in hud_c:
                continue
            patch = grid[r:r + ah, c:c + aw]
            matches = sum(1 for v in patch.flat if v in profile.avatar_colors)
            if matches > best_score and matches >= max(1, (ah * aw) // 3):
                best_score = matches
                best_pos = (r, c)

    return best_pos


