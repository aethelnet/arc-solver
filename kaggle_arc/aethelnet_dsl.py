class AethelnetGameOntology:
    """Decomposes board into ontological archetypes and infers structural affinities."""

    @staticmethod
    def extract_entities(frame: Any) -> Tuple[str, List[OntologyEntity]]:
        lines = _to_lines(frame)
        H = len(lines)
        W = len(lines[0]) if H > 0 else 0
        if H == 0 or W == 0:
            return '.', []

        total_counts = collections.Counter("".join(lines))
        if '.' in total_counts and total_counts['.'] >= (H * W) * 0.15:
            bg_char = '.'
        elif '0' in total_counts and total_counts['0'] >= (H * W) * 0.15:
            bg_char = '0'
        else:
            border_chars = []
            for c in range(W):
                border_chars.append(lines[0][c])
                border_chars.append(lines[H - 1][c])
            for r in range(H):
                border_chars.append(lines[r][0])
                border_chars.append(lines[r][W - 1])
            counts = collections.Counter(border_chars)
            bg_char = counts.most_common(1)[0][0] if counts else (total_counts.most_common(1)[0][0] if total_counts else '.')

        visited = set()
        entities: List[OntologyEntity] = []
        ent_id = 1

        for r in range(H):
            for c in range(W):
                char = lines[r][c]
                if char != bg_char and (r, c) not in visited:
                    cluster = []
                    queue = collections.deque([(r, c)])
                    visited.add((r, c))
                    while queue:
                        cr, cc = queue.popleft()
                        cluster.append((cr, cc))
                        for dr, dc in [(-1, 0), (1, 0), (0, -1), (0, 1)]:
                            nr, nc = cr + dr, cc + dc
                            if 0 <= nr < H and 0 <= nc < W and (nr, nc) not in visited and lines[nr][nc] == char:
                                visited.add((nr, nc))
                                queue.append((nr, nc))

                    rs = [p[0] for p in cluster]
                    cs = [p[1] for p in cluster]
                    min_r, max_r = min(rs), max(rs)
                    min_c, max_c = min(cs), max(cs)
                    area = len(cluster)
                    eh = max_r - min_r + 1
                    ew = max_c - min_c + 1
                    bbox_area = eh * ew
                    center = (int(round(sum(rs) / area)), int(round(sum(cs) / area)))

                    is_hollow = False
                    inner_area = 0
                    if eh >= 3 and ew >= 3 and area < bbox_area:
                        inner_pts = set()
                        for ir in range(min_r + 1, max_r):
                            for ic in range(min_c + 1, max_c):
                                if (ir, ic) not in cluster:
                                    inner_pts.add((ir, ic))
                        if inner_pts:
                            is_hollow = True
                            inner_area = len(inner_pts)

                    archetype = "OBSTACLE"
                    if (min_r == 0 or max_r == H - 1) and ew >= W - 4 and area >= W - 4:
                        archetype = "HUD"
                    elif is_hollow:
                        archetype = "GOAL"
                    elif (eh == 1 and ew >= 3 and 1 < min_r < H - 2) or (ew == 1 and eh >= 3 and 1 < min_c < W - 2):
                        archetype = "GATE"
                    elif area <= 9 and eh <= 3 and ew <= 3:
                        archetype = "ACTUATOR"
                    elif area <= 36 and not is_hollow:
                        archetype = "PUSHABLE"
                    elif area > 100:
                        archetype = "OBSTACLE"

                    entities.append(OntologyEntity(
                        id=ent_id,
                        color=char,
                        archetype=archetype,
                        bbox=(min_r, min_c, max_r, max_c),
                        area=area,
                        is_hollow=is_hollow,
                        inner_area=inner_area,
                        center=center
                    ))
                    ent_id += 1

        # Second pass refinement: group tiny recurring items into COLLECTIBLE
        spec_counts = collections.Counter((e.color, e.area) for e in entities)
        for e in entities:
            if e.archetype == "ACTUATOR" and spec_counts[(e.color, e.area)] >= 3:
                e.archetype = "COLLECTIBLE"

        return bg_char, entities

    @staticmethod
    def match_slot_cargo(entities: List[OntologyEntity]) -> List[Dict[str, Any]]:
        """Matches solid cargo blocks to hollow slots/receptors by dimension and shape congruence."""
        cargos = [e for e in entities if e.archetype in ("PUSHABLE", "ACTUATOR") and not e.is_hollow and e.area >= 2]
        slots = [e for e in entities if e.is_hollow or e.archetype == "GOAL"]
        matches = []

        for c in cargos:
            for s in slots:
                score = 0.0
                if s.inner_area > 0:
                    area_diff = abs(c.area - s.inner_area)
                    if area_diff == 0:
                        score += 0.5
                    elif area_diff <= 2:
                        score += 0.3
                sw, sh = s.dimensions
                cw, ch = c.dimensions
                if cw <= sw and ch <= sh:
                    score += 0.3
                if c.color == s.color:
                    score += 0.2

                if score >= 0.5:
                    matches.append({
                        "cargo_id": c.id,
                        "slot_id": s.id,
                        "cargo_color": c.color,
                        "slot_color": s.color,
                        "cargo_pos": c.center,
                        "slot_pos": s.center,
                        "score": round(score, 2)
                    })
        return sorted(matches, key=lambda x: x["score"], reverse=True)

    @staticmethod
    def detect_blueprints(frame: Any, entities: List[OntologyEntity]) -> List[Dict[str, Any]]:
        """Identifies small isolated template windows in corners that depict goal shapes."""
        lines = _to_lines(frame)
        H = len(lines)
        W = len(lines[0]) if H > 0 else 0
        if H == 0 or W == 0:
            return []
        blueprints = []

        bs = max(6, min(14, H // 3, W // 3))
        corner_boxes = [
            ("TOP_LEFT", (0, 0, bs, bs)),
            ("TOP_RIGHT", (0, max(0, W - bs), bs, W - 1)),
            ("BOTTOM_LEFT", (max(0, H - bs), 0, H - 1, min(W - 1, bs))),
            ("BOTTOM_RIGHT", (max(0, H - bs), max(0, W - bs), H - 1, W - 1)),
        ]

        for name, (r1, c1, r2, c2) in corner_boxes:
            box_ents = [e for e in entities if r1 <= e.bbox[0] and e.bbox[2] <= r2 and c1 <= e.bbox[1] and e.bbox[3] <= c2]
            colors = {e.color for e in box_ents if e.archetype != "HUD"}
            total_area = sum(e.area for e in box_ents)
            if len(colors) >= 2 and 4 <= total_area <= 60:
                blueprints.append({
                    "location": name,
                    "bbox": (r1, c1, r2, c2),
                    "colors": sorted(list(colors)),
                    "description": f"Static template in {name} with colors {sorted(list(colors))}"
                })
        return blueprints

    @staticmethod
    def detect_actuator_affordances(entities: List[OntologyEntity]) -> List[Dict[str, Any]]:
        """Maps switches/actuators to corresponding gates or goals based on color alignment."""
        actuators = [e for e in entities if e.archetype == "ACTUATOR"]
        targets = [e for e in entities if e.archetype in ("GATE", "GOAL", "OBSTACLE", "PUSHABLE")]
        affordances = []

        for act in actuators:
            for tgt in targets:
                if act.id != tgt.id and act.color == tgt.color:
                    affordances.append({
                        "actuator_id": act.id,
                        "target_id": tgt.id,
                        "color": act.color,
                        "actuator_pos": act.center,
                        "target_pos": tgt.center,
                        "target_archetype": tgt.archetype,
                        "description": f"Switch #{act.id} at {act.center} (color '{act.color}') matches {tgt.archetype} #{tgt.id} at {tgt.center}"
                    })
        return affordances

    @staticmethod
    def generate_hypotheses(frame: Any) -> List[str]:
        """Generates compact, high-confidence inductive hypotheses for LLM prompt."""
        bg_char, entities = AethelnetGameOntology.extract_entities(frame)
        if not entities:
            return []

        hypotheses = []
        matches = AethelnetGameOntology.match_slot_cargo(entities)
        for m in matches[:3]:
            hypotheses.append(
                f"[SLOT-CARGO] Entity #{m['cargo_id']} (col '{m['cargo_color']}', pos {m['cargo_pos']}) "
                f"congruent with Slot #{m['slot_id']} (col '{m['slot_color']}', pos {m['slot_pos']}) [score: {m['score']:.2f}]"
            )

        affordances = AethelnetGameOntology.detect_actuator_affordances(entities)
        for a in affordances[:2]:
            hypotheses.append(
                f"[ACTUATOR] Switch #{a['actuator_id']} at {a['actuator_pos']} (col '{a['color']}') "
                f"matches {a['target_archetype']} #{a['target_id']} at {a['target_pos']}"
            )

        blueprints = AethelnetGameOntology.detect_blueprints(frame, entities)
        for b in blueprints[:2]:
            hypotheses.append(f"[BLUEPRINT] Goal template in {b['location']} with colors {b['colors']}")

        return hypotheses


