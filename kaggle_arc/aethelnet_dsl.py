def is_corner_deadlock(
    frame_or_grid: Any,
    pos: Union[Tuple[int, int], Tuple[int, int, int, int]],
    goal_coords: Optional[Set[Tuple[int, int]]] = None,
    solid_mask: Optional[np.ndarray] = None,
    exclude_coords: Optional[Set[Tuple[int, int]]] = None
) -> bool:
    """
    Evaluates whether placing a movable solid entity at pos=(r, c) or bbox=(r1, c1, r2, c2)
    creates an irreversible 90-degree corner deadlock against non-walkable boundaries.
    """
    if len(pos) == 2:
        min_r, min_c = pos
        max_r, max_c = pos
    else:
        min_r, min_c, max_r, max_c = pos

    if goal_coords:
        for gr in range(min_r, max_r + 1):
            for gc in range(min_c, max_c + 1):
                if (gr, gc) in goal_coords:
                    return False

    mask = None
    if solid_mask is not None:
        if isinstance(solid_mask, np.ndarray) and solid_mask.ndim == 2:
            mask = solid_mask.copy()
            H, W = mask.shape
        else:
            try:
                sm = np.asarray(solid_mask, dtype=bool)
                if sm.ndim == 2:
                    mask = sm.copy()
                    H, W = mask.shape
            except Exception:
                mask = None

    if mask is None:
        lines = _to_lines(frame_or_grid)
        H = len(lines)
        W = len(lines[0]) if H > 0 else 0
        if H == 0 or W == 0:
            return False
        bg, entities = AethelnetGameOntology.extract_entities(frame_or_grid)
        mask = np.zeros((H, W), dtype=bool)

        for e in entities:
            if e.archetype in ("OBSTACLE", "HUD"):
                er1, ec1, er2, ec2 = e.bbox
                for row in range(er1, er2 + 1):
                    for col in range(ec1, ec2 + 1):
                        if lines[row][col] == e.color:
                            mask[row, col] = True

        if not np.any(mask):
            for row in range(H):
                for col in range(W):
                    if lines[row][col] != bg and lines[row][col] not in ('.', '0'):
                        mask[row, col] = True

    if exclude_coords:
        for er, ec in exclude_coords:
            if 0 <= er < H and 0 <= ec < W:
                mask[er, ec] = False

    up_blocked = (min_r <= 0) or any(mask[min_r - 1, c] for c in range(min_c, max_c + 1) if min_r - 1 < H and c < W)
    down_blocked = (max_r >= H - 1) or any(mask[max_r + 1, c] for c in range(min_c, max_c + 1) if max_r + 1 < H and c < W)
    left_blocked = (min_c <= 0) or any(mask[r, min_c - 1] for r in range(min_r, max_r + 1) if min_c - 1 < W and r < H)
    right_blocked = (max_c >= W - 1) or any(mask[r, max_c + 1] for r in range(min_r, max_r + 1) if max_c + 1 < W and r < H)

    is_corner = (up_blocked or down_blocked) and (left_blocked or right_blocked)
    return bool(is_corner)


def evaluate_push_deadlock(
    frame_or_grid: Any,
    box_pos: Union[Tuple[int, int], Tuple[int, int, int, int]],
    push_action: Union[int, str],
    goal_coords: Optional[Set[Tuple[int, int]]] = None,
    solid_mask: Optional[np.ndarray] = None
) -> Tuple[bool, Optional[str]]:
    """
    Returns (True, reason) if executing push_action on box at box_pos
    would push it into an irreversible corner deadlock.
    """
    if push_action not in ACTION_TO_DIR:
        return False, None

    if isinstance(box_pos, (list, np.ndarray)):
        box_pos = tuple(box_pos)
    dr, dc = ACTION_TO_DIR[push_action]
    if len(box_pos) == 2:
        r, c = box_pos
        target_pos = (r + dr, c + dc)
        exclude = {tuple(box_pos)}
    else:
        r1, c1, r2, c2 = box_pos
        target_pos = (r1 + dr, c1 + dc, r2 + dr, c2 + dc)
        exclude = {(r, c) for r in range(r1, r2 + 1) for c in range(c1, c2 + 1)}

    if is_corner_deadlock(frame_or_grid, target_pos, goal_coords, solid_mask=solid_mask, exclude_coords=exclude):
        return True, f"Pushing cargo from {box_pos} to {target_pos} creates permanent corner deadlock."
    return False, None


