# 4. Sokoban / Push-A* Routing
# =============================================================================

def plan_push_box(
    avatar_pos: Tuple[int, int],
    box_pos: Tuple[int, int],
    target_slot: Tuple[int, int],
    solid_mask: np.ndarray,
    stride: int = 1,
    as_strings: bool = True
) -> List[Any]:
    """
    Push-A* Sokoban planner:
    Calculates push trajectory to move box into target_slot,
    generating avatar navigation moves to the push pose behind the box for each push.
    """
    s = stride
    if solid_mask is None or not hasattr(solid_mask, "shape") or len(solid_mask.shape) != 2:
        return []
    H, W = solid_mask.shape

    # State: (box_r, box_c, avatar_r, avatar_c)
    # A* search over box positions
    open_heap = []
    # (f_cost, g_cost, (box_r, box_c), (av_r, av_c), moves_list)
    h0 = (abs(box_pos[0] - target_slot[0]) + abs(box_pos[1] - target_slot[1])) // s
    heapq.heappush(open_heap, (h0, 0, box_pos, avatar_pos, []))
    visited_states = set()

    while open_heap:
        f, g, b_curr, a_curr, moves = heapq.heappop(open_heap)
        if abs(b_curr[0] - target_slot[0]) < s and abs(b_curr[1] - target_slot[1]) < s:
            if as_strings:
                return [DIR_TO_ACTION_NAME[ACTION_TO_DIR[m]] if isinstance(m, int) else m for m in moves]
            return moves

        state_key = (b_curr, a_curr)
        if state_key in visited_states or len(moves) > 150:
            continue
        visited_states.add(state_key)

        # Try pushing box in 4 directions
        for d_act in [1, 2, 3, 4]:
            dr, dc = ACTION_TO_DIR[d_act]
            next_b = (b_curr[0] + dr * s, b_curr[1] + dc * s)
            push_pose = (b_curr[0] - dr * s, b_curr[1] - dc * s)

            # Check next box validity
            if not (0 <= next_b[0] <= H - s and 0 <= next_b[1] <= W - s):
                continue
            if np.any(solid_mask[next_b[0]:next_b[0] + s, next_b[1]:next_b[1] + s]):
                continue

            # Check push pose validity
            if not (0 <= push_pose[0] <= H - s and 0 <= push_pose[1] <= W - s):
                continue
            if np.any(solid_mask[push_pose[0]:push_pose[0] + s, push_pose[1]:push_pose[1] + s]):
                continue

            # Route avatar to push pose treating box as obstacle
            box_barrier = solid_mask.copy()
            box_barrier[b_curr[0]:b_curr[0] + s, b_curr[1]:b_curr[1] + s] = True

            nav_moves = plan_bfs_path(a_curr, push_pose, box_barrier, stride=s, as_strings=False)
            if a_curr == push_pose or nav_moves or (abs(a_curr[0] - push_pose[0]) < s and abs(a_curr[1] - push_pose[1]) < s):
                total_step_moves = moves + nav_moves + [d_act]
                new_av = b_curr  # Avatar moves into old box position
                new_g = g + len(nav_moves) + 1
                new_h = (abs(next_b[0] - target_slot[0]) + abs(next_b[1] - target_slot[1])) // s
                heapq.heappush(open_heap, (new_g + new_h, new_g, next_b, new_av, total_step_moves))

    return []


