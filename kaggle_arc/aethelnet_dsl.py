class RealActiveInferenceSolver:
    """
    Full autonomous active inference player for any ARC-AGI-3 environment.
    Runs whenever the LLM is dormant, stalled, or when low-level execution is needed.
    """
    def __init__(self, game_id: str = "default"):
        self.game_id = game_id
        self.level_resets = collections.defaultdict(int)
        self.reset_all()

    def reset_all(self):
        self.current_level = 0
        self.step_count = 0
        self.prev_grid = None
        self.last_action = None
        self.last_action_data = None
        self.calibrated = False
        self.probe_step = 0
        self.profile = KinematicsProfile()
        self.avatar_pos = None
        self.hud_rows = set()
        self.hud_cols = set()
        self.deadly_coords = set()
        self.visited_tiles = set()
        self.visit_counts = collections.defaultdict(int)
        self.plan_queue = []
        self.click_queue = []
        self.click_tested = set()
        self.level_resets.clear()

    def reset_level(self, level: int):
        self.current_level = level
        self.prev_grid = None
        self.last_action = None
        self.last_action_data = None
        self.plan_queue.clear()
        self.click_queue.clear()
        self.visited_tiles.clear()
        self.visit_counts.clear()
        self.avatar_pos = None

    def choose_action(
        self,
        grid: np.ndarray,
        available_actions: List[int],
        levels_completed: int,
        state_name: str
    ) -> Tuple[int, Optional[Dict[str, Any]], str]:
        self.step_count += 1
        grid = np.asarray(grid)

        # 1. Level Transition Handler
        if levels_completed > self.current_level:
            self.reset_level(levels_completed)

        # 2. Episodic Death Memory & Reset Handler
        if state_name in ('GAME_OVER', 'NOT_PLAYED'):
            if state_name == 'GAME_OVER' and self.avatar_pos is not None and self.last_action in ACTION_TO_DIR:
                dr, dc = ACTION_TO_DIR[self.last_action]
                s = self.profile.stride
                fatal_r = self.avatar_pos[0] + dr * s
                fatal_c = self.avatar_pos[1] + dc * s
                self.deadly_coords.add((fatal_r, fatal_c))
            self.reset_level(levels_completed)
            return (0, None, "GameReset")

        # 2b. Controlled Reset on Irreversible Cargo Deadlock
        _, entities = AethelnetGameOntology.extract_entities(grid)
        goals = set()
        for e in entities:
            if e.archetype == "GOAL" and e.archetype not in ("HUD", "OBSTACLE"):
                min_r, min_c, max_r, max_c = e.bbox
                for r in range(min_r, max_r + 1):
                    for c in range(min_c, max_c + 1):
                        goals.add((r, c))
                goals.add(e.center)
        cargos = [e for e in entities if e.archetype in ("PUSHABLE", "ACTUATOR") and not e.is_hollow and e.area >= 2]

        vault = AethelnetVault.get_instance(self.game_id)
        if cargos and (0 in available_actions or 'RESET' in available_actions):
            for cargo in cargos:
                if is_corner_deadlock(grid, cargo.bbox, goals) or is_corner_deadlock(grid, cargo.center, goals):
                    if self.level_resets[levels_completed] < 2:
                        self.level_resets[levels_completed] += 1
                        sig = f"lvl{levels_completed}_box{cargo.center}"
                        vault.remember_nogood(
                            level=levels_completed,
                            state_signature=sig,
                            forbidden_action=self.last_action if self.last_action is not None else 0,
                            reason=f"Cargo at {cargo.center} permanently trapped in non-goal corner",
                            turn=self.step_count
                        )
                        self.reset_level(levels_completed)
                        return (0, None, f"ControlledReset_DeadlockCargo_{cargo.center}")

        # 3. Pure Click Mode Handler (Action 6 only)
        is_pure_click = (available_actions == [6]) or (6 in available_actions and not any(a in [1, 2, 3, 4] for a in available_actions))
        if is_pure_click:
            if not self.click_queue:
                centroids = extract_clickable_targets(grid, self.hud_rows, self.hud_cols)
                self.click_queue = [pt for pt in centroids if pt not in self.click_tested]
                if not self.click_queue:
                    self.click_queue = centroids

            if self.click_queue:
                cx, cy = self.click_queue.pop(0)
                self.click_tested.add((cx, cy))
                self.last_action = 6
                self.last_action_data = {'x': int(cx), 'y': int(cy)}
                self.prev_grid = grid.copy()
                return (6, {'x': int(cx), 'y': int(cy)}, f"ClickTarget_{cx}_{cy}")

        # 4. Plan Queue Execution
        if self.plan_queue:
            act, data = self.plan_queue.pop(0)
            if act in available_actions:
                vetoed = False
                if act in ACTION_TO_DIR and self.avatar_pos is not None:
                    ar, ac = self.avatar_pos
                    dr, dc = ACTION_TO_DIR[act]
                    s = self.profile.stride
                    nr, nc = ar + dr * s, ac + dc * s
                    for cargo in cargos:
                        min_r, min_c, max_r, max_c = cargo.bbox
                        if min_r <= nr <= max_r and min_c <= nc <= max_c:
                            deadlock, _ = evaluate_push_deadlock(grid, cargo.center, act, goals)
                            if deadlock:
                                vetoed = True
                                break
                if vetoed:
                    self.plan_queue.clear()
                else:
                    self.last_action = act
                    self.last_action_data = data
                    self.prev_grid = grid.copy()
                    return (act, data, "ExecutingPlan")
            else:
                self.plan_queue.clear()

        # 5. Calibration Probe
        if not self.calibrated:
            if self.prev_grid is not None and self.last_action is not None:
                hr, hc = detect_hud_bars(self.prev_grid, grid)
                self.hud_rows.update(hr)
                self.hud_cols.update(hc)
                prof = calibrate_kinematics_probe(self.prev_grid, grid, self.last_action)
                if prof is not None:
                    self.profile = prof
                    self.calibrated = True
                    self.avatar_pos = locate_avatar_on_grid(grid, self.profile, self.hud_rows, self.hud_cols)

            if not self.calibrated:
                probe_cands = [a for a in [4, 2, 3, 1] if a in available_actions]
                act = probe_cands[self.probe_step % len(probe_cands)] if probe_cands else available_actions[0]
                self.probe_step += 1
                self.last_action = act
                self.last_action_data = None
                self.prev_grid = grid.copy()
                return (act, None, f"CalibrationProbe_{act}")

        # 6. Locate Avatar
        self.avatar_pos = locate_avatar_on_grid(grid, self.profile, self.hud_rows, self.hud_cols)

        # 7. Navigation & Goal Seeking
        if self.avatar_pos is not None:
            H, W = grid.shape
            bg = get_background_color(grid)
            counts = collections.Counter(grid.flatten())
            non_bg = [c for c, _ in counts.most_common() if c != bg]
            wall_color = non_bg[0] if non_bg else bg
            solid_mask = (grid == wall_color)

            for hr in self.hud_rows:
                solid_mask[hr, :] = True
            for hc in self.hud_cols:
                solid_mask[:, hc] = True

            centroids = extract_clickable_targets(grid, self.hud_rows, self.hud_cols)
            ar, ac = self.avatar_pos

            for target_c, target_r in centroids:
                if (target_r, target_c) == (ar, ac):
                    continue
                path = plan_bfs_path((ar, ac), (target_r, target_c), solid_mask, stride=self.profile.stride,
                                     deadly_coords=self.deadly_coords, legal_actions=available_actions, as_strings=False)
                if path:
                    first_act = path[0]
                    self.plan_queue = [(a, None) for a in path[1:]]
                    self.last_action = first_act
                    self.last_action_data = None
                    self.prev_grid = grid.copy()
                    return (first_act, None, f"NavigatingTo_{target_r}_{target_c}")

            # Fallback: exploratory move minimizing visit counts & vetoing deadlocks
            self.visit_counts[self.avatar_pos] += 1
            legal_moves = [a for a in [1, 2, 3, 4] if a in available_actions]
            s = self.profile.stride
            best_act = None
            min_visits = 999999

            for act in legal_moves:
                dr, dc = ACTION_TO_DIR[act]
                nr, nc = ar + dr * s, ac + dc * s
                if 0 <= nr <= H - s and 0 <= nc <= W - s:
                    if not np.any(solid_mask[nr:nr + s, nc:nc + s]) and (nr, nc) not in self.deadly_coords:
                        # Deadlock veto for pushable entities
                        is_deadlock = False
                        for cargo in cargos:
                            min_r, min_c, max_r, max_c = cargo.bbox
                            if min_r <= nr <= max_r and min_c <= nc <= max_c:
                                deadlock, reason = evaluate_push_deadlock(grid, cargo.center, act, goals)
                                if deadlock:
                                    is_deadlock = True
                                    sig = f"lvl{levels_completed}_box{cargo.center}_av({ar},{ac})"
                                    vault.remember_nogood(levels_completed, sig, act, reason or "Corner deadlock", turn=self.step_count)
                                    break
                        if is_deadlock:
                            continue

                        # Conflict-driven nogood clause check
                        sig1 = f"lvl{levels_completed}_av({ar},{ac})"
                        is_ng, _ = vault.is_action_nogood(levels_completed, sig1, act)
                        if not is_ng:
                            for cargo in cargos:
                                sig2 = f"lvl{levels_completed}_box{cargo.center}_av({ar},{ac})"
                                is_ng2, _ = vault.is_action_nogood(levels_completed, sig2, act)
                                if is_ng2:
                                    is_ng = True
                                    break
                        if is_ng:
                            continue

                        vc = self.visit_counts[(nr, nc)]
                        if vc < min_visits:
                            min_visits = vc
                            best_act = act

            if best_act is not None:
                self.last_action = best_act
                self.last_action_data = None
                self.prev_grid = grid.copy()
                return (best_act, None, f"ExploratoryMove_{best_act}")

        # 8. Dynamic Legal Fallback
        cands = [a for a in available_actions if a != 0]
        act = cands[0] if cands else 1
        data = None
        if act == 6:
            centroids = extract_clickable_targets(grid, self.hud_rows, self.hud_cols)
            cx, cy = centroids[0] if centroids else (32, 32)
            data = {'x': int(cx), 'y': int(cy)}

        self.last_action = act
        self.last_action_data = data
        self.prev_grid = grid.copy()
        return (int(act), data, "DynamicFallback")


