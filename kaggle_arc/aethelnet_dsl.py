def _to_lines(frame: Any) -> List[str]:
    """Converts diverse state representations into list of strings representing 2D grid."""
    if frame is None:
        return []
    if isinstance(frame, np.ndarray):
        if frame.size == 0:
            return []
        while frame.ndim > 2:
            frame = frame[0]
        if frame.ndim == 1:
            return ["".join(f"{val:X}" if isinstance(val, (int, np.integer)) else str(val) for val in frame)]
        return ["".join(f"{val:X}" if isinstance(val, (int, np.integer)) else str(val) for val in row) for row in frame]
    if hasattr(frame, 'ascii') and isinstance(frame.ascii, str):
        return [l for l in frame.ascii.splitlines() if l]
    if hasattr(frame, 'grid') and frame.grid is not None:
        return _to_lines(frame.grid)
    if isinstance(frame, list):
        if not frame:
            return []
        if isinstance(frame[0], str):
            return list(frame)
        lines = []
        for row in frame:
            if isinstance(row, (list, tuple, np.ndarray)):
                lines.append("".join(f"{val:X}" if isinstance(val, (int, np.integer)) else str(val) for val in row))
            elif isinstance(row, str):
                lines.append(row)
            else:
                lines.append(f"{row:X}" if isinstance(row, (int, np.integer)) else str(row))
        return lines
    if isinstance(frame, str):
        return [l for l in frame.splitlines() if l]
    return []



def diff_frames(f1: Any, f2: Any) -> List[Tuple[int, int, str, str]]:
    """Returns list of (row, col, old_char, new_char) that changed between f1 and f2."""
    lines1 = _to_lines(f1)
    lines2 = _to_lines(f2)
    diffs = []
    for r in range(min(len(lines1), len(lines2))):
        l1, l2 = lines1[r], lines2[r]
        for c in range(min(len(l1), len(l2))):
            if l1[c] != l2[c]:
                diffs.append((r, c, l1[c], l2[c]))
    return diffs


def read_patch(frame: Any, r1: int, r2: int, c1: int, c2: int) -> str:
    """Returns ASCII crop of region [r1..r2, c1..c2]."""
    lines = _to_lines(frame)
    if not lines:
        return ""
    rows = []
    for r in range(max(0, r1), min(len(lines), r2 + 1)):
        rows.append(lines[r][max(0, c1):min(len(lines[r]), c2 + 1)])
    return "\n".join(rows)


def find_color_centers(frame: Any, color_char: str) -> List[Tuple[int, int]]:
    """Returns (row, col) center points for all connected clusters of color_char."""
    lines = _to_lines(frame)
    if not lines:
        return []
    H = len(lines)
    W = len(lines[0]) if H > 0 else 0
    visited = set()
    centers = []
    for r in range(H):
        for c in range(W):
            if lines[r][c] == color_char and (r, c) not in visited:
                cluster = []
                queue = collections.deque([(r, c)])
                visited.add((r, c))
                while queue:
                    cr, cc = queue.popleft()
                    cluster.append((cr, cc))
                    for dr, dc in [(-1, 0), (1, 0), (0, -1), (0, 1)]:
                        nr, nc = cr + dr, cc + dc
                        if 0 <= nr < H and 0 <= nc < W and (nr, nc) not in visited and lines[nr][nc] == color_char:
                            visited.add((nr, nc))
                            queue.append((nr, nc))
                avg_r = int(round(sum(p[0] for p in cluster) / len(cluster)))
                avg_c = int(round(sum(p[1] for p in cluster) / len(cluster)))
                centers.append((avg_r, avg_c))
    return centers


